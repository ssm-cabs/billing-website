/* eslint-disable no-console */
const admin = require("firebase-admin");

if (!admin.apps.length) {
  admin.initializeApp();
}

const db = admin.firestore();
const LEGACY_MARKER = "[autogenerated]";
const SAMPLE_LIMIT = 30;

async function scanEntriesNotes() {
  const snapshot = await db.collection("entries").get();
  let scanned = 0;
  let legacyHits = 0;
  const samples = [];

  for (const docSnap of snapshot.docs) {
    scanned += 1;
    const data = docSnap.data() || {};
    const notes = String(data.notes || "");
    if (!notes.includes(LEGACY_MARKER)) continue;

    legacyHits += 1;
    if (samples.length < SAMPLE_LIMIT) {
      samples.push({
        entry_id: data.entry_id || docSnap.id,
        doc_id: docSnap.id,
      });
    }
  }

  return { scanned, legacyHits, samples };
}

async function main() {
  console.log("Checking legacy auto-note marker usage in entries.notes...");
  const result = await scanEntriesNotes();

  console.log(`Scanned entries: ${result.scanned}`);
  console.log(`Entries containing "${LEGACY_MARKER}": ${result.legacyHits}`);

  if (result.samples.length) {
    console.log("\nSample entries with legacy marker:");
    result.samples.forEach((item) => {
      console.log(`- entry_id=${item.entry_id}, doc_id=${item.doc_id}`);
    });
  }

  if (result.legacyHits === 0) {
    console.log(
      '\nNo legacy markers found. You can safely remove legacy marker handling from code.'
    );
  } else {
    console.log(
      "\nLegacy markers still exist. Keep legacy marker handling until those notes are regenerated/cleaned."
    );
  }
}

main().catch((error) => {
  console.error("Check failed:", error);
  process.exitCode = 1;
});
